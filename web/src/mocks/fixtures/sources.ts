/** Splits a paragraph list into retrieval-sized chunks with a 15% overlap. */
function buildChunks(pages: SourcePage[], seed: number): SourceChunk[] {
  const random = mulberry32(seed);
  const chunks: SourceChunk[] = [];
  let index = 0;

  for (const page of pages) {
    const paragraphs = page.text.split(/\n{2,}/).filter(Boolean);
    let buffer = '';
    const flush = () => {
      const text = buffer.trim();
      if (!text) return;
      chunks.push({
        id: `chunk_${seed}_${index}`,
        index,
        page: page.index,
        text,
        tokens: Math.round(text.length / 3) + Math.round(random() * 8),
      });
      index += 1;
      const overlap = text.slice(Math.max(0, text.length - Math.round(text.length * 0.15)));
      buffer = overlap.includes(' ') ? `${overlap.slice(overlap.indexOf(' '))} ` : '';
    };

    for (const paragraph of paragraphs) {
      if (buffer.length + paragraph.length > 1150 && buffer.length > 0) flush();
      buffer += `${paragraph}\n\n`;
      if (buffer.length > 1500) flush();
    }
    flush();
  }

  return chunks;
}

export function buildPages(spec: SourceSpec): SourcePage[] {
  const random = mulberry32(spec.id.length * 7919 + spec.pageCount);
  const pages: SourcePage[] = [];

  for (let i = 0; i < spec.pageCount; i += 1) {
    const handwritten = spec.openingPages[i];
    let text: string;
    if (handwritten) {
      text = handwritten;
    } else if (spec.sentences.length === 0) {
      text = 'Страница не содержит распознанного текста.';
    } else {
      const take = 5 + Math.floor(random() * 4);
      const picked: string[] = [];
      for (let s = 0; s < take; s += 1) {
        picked.push(spec.sentences[Math.floor(random() * spec.sentences.length)]);
      }
      const heading = `Раздел ${Math.ceil((i + 1) / 4)}.${((i + 1) % 4) + 1}`;
      text = `${heading}\n\n${picked.join(' ')}`;
      if (random() > 0.45) {
        text += `\n\nДополнительно: ${picked.slice(0, 2).join(' ')}`;
      }
    }
    pages.push({
      index: i,
      text,
      chars: text.length,
      ...(spec.kind === 'image' ? { confidence: 0.86 + random() * 0.12 } : {}),
    });
  }

  return pages;
}

export function buildContent(spec: SourceSpec): SourceContent {
  const pages = buildPages(spec);
  const chunks = buildChunks(pages, spec.id.length * 104729 + spec.pageCount);
  return { source_id: spec.id, pages, chunks };
}

function materialize(spec: SourceSpec): { source: KnowledgeSource; content: SourceContent } {
  const content = buildContent(spec);
  const failed = spec.status === 'error';
  const processing = spec.status === 'processing' || spec.status === 'uploading';
  const token_count = content.chunks.reduce((sum, chunk) => sum + chunk.tokens, 0);
  const created_at = ago(spec.ageHours * HOUR);

  return {
    source: {
      id: spec.id,
      mode_id: spec.mode_id,
      title: spec.title,
      filename: spec.filename,
      media_type: spec.kind === 'image' ? 'image/jpeg' : 'application/pdf',
      processing_mode: spec.processing_mode,
      status: spec.status,
      page_count: failed ? 0 : content.pages.length,
      chunk_count: failed ? 0 : content.chunks.length,
      token_count: failed ? 0 : token_count,
      error: spec.error ?? null,
      created_at,
      updated_at: failed ? created_at : ago(Math.max(0.05, spec.ageHours * 0.6) * HOUR),
      progress: failed ? 0 : processing ? 0.34 : 1,
      stage: processing ? 'Распознавание текста' : null,
    },
    content,
  };
}

